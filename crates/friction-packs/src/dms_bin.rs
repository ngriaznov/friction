//! Derived binary DMS artifact: the pre-built suffix automata
//! `packs/dms-index-en-v1.toml` describes, serialized flat so runtime never
//! builds them again.
//!
//! # Why this exists
//!
//! [`crate::DmsIndex::parse`] is the audited read side of the TOML pack
//! `corpus-tool index` writes, and stays the source of truth — but it
//! pays a real price on every process start: parsing ~2.5 MB of TOML and
//! then running [`crate::Sam`]'s reference `extend` loop over every
//! stream, allocating one `HashMap` per automaton state. That
//! construction was the whole of `friction`'s measured fixed startup
//! cost (~90 ms), dwarfing the actual work on README-sized documents.
//!
//! This module is the same cure the perceptron weights already received
//! (`friction-nlp`'s `weights_bin`, format version 2): do the expensive
//! construction **once, offline**, in `corpus-tool dms-pack`, and
//! serialize the finished automata in a layout the runtime can use as a
//! zero-copy view over the `include_bytes!`'d static: a handful of
//! slice splits at load, no per-state work at all.
//!
//! # Layout
//!
//! A fixed header, then little-endian sections. Every multi-byte field is
//! read via `from_le_bytes` on a byte slice — alignment-free by
//! construction, so no `unsafe` is ever needed (this workspace denies
//! `unsafe_code`).
//!
//! - **Header**: 8-byte magic `FRDMSIDX`, `u16` format version, 64-byte
//!   lowercase-hex sha256 of the source TOML this artifact was packed
//!   from. Recording the source sha lets a stale `.bin` (TOML
//!   regenerated by `corpus-tool index`, `dms-pack` not re-run) fail
//!   loudly in this crate's own drift test rather than silently serving
//!   automata built from an older corpus.
//! - **Vocab**: token count `n`; `n + 1` cumulative `u32` byte offsets
//!   into a string pool; the pool itself (`u32` length prefix); and a
//!   lookup table of token ids sorted by token text (`u32` count, then
//!   that many `u32` ids) for [`VocabView::id_of`]'s binary search.
//!   Duplicate texts (tolerated by [`crate::Vocab`], resolved
//!   first-id-wins) are collapsed to their first id at pack time, so the
//!   sorted table's texts are strictly increasing and the search is
//!   unambiguous.
//! - **Streams**: stream count, then per stream a `u32` tag (`0` =
//!   human, `1 + ModelFamily::ALL` position for a per-family stream,
//!   [`POOLED_MACHINE_TAG`] for the pooled machine stream — see below)
//!   and one serialized automaton: state count `s`; `s` `u32` `len`
//!   values; `s` `u32` suffix links ([`ROOT_LINK_SENTINEL`] for the
//!   root's `None`); `s + 1` cumulative `u32` transition offsets (CSR);
//!   then the transition array, 8 bytes per edge (`label: u32`,
//!   `target: u32`), sorted by label within each state so [`SamView`]
//!   can binary-search where [`crate::Sam`] hash-probes.
//!
//! # Format version 2: the pooled machine stream
//!
//! Version 2 adds exactly one more stream to the section above, tagged
//! [`POOLED_MACHINE_TAG`]: [`crate::DmsIndex::pooled_machine_sam`], every
//! present family stream's ids concatenated in fixed alphabetical order
//! with the document separator between streams (see that method's own
//! docs). The five per-family sections from version 1 are unchanged and
//! still written — kept for `family_sam`/`--family` compatibility: the
//! pooled stream is additive, not a replacement. A version-1 artifact (no
//! pooled section) is rejected by [`DmsIndexView::parse`] as a
//! [`DmsBinError::VersionMismatch`]; there is no reader that accepts
//! both, since every producer (`corpus-tool dms-pack`) and consumer (this
//! crate's embedded artifact) ship together.
//!
//! # Determinism
//!
//! [`pack_dms_index_bin`] is a pure function of the TOML text:
//! [`crate::Sam`]'s build is deterministic (documented on the type), the
//! only `HashMap` iteration is explicitly sorted
//! (`Sam::sorted_transitions`), the vocab's duplicate collapse follows
//! `BTreeMap` order, and streams are written human-first, then
//! [`ModelFamily::ALL`] order, then the pooled machine stream last:
//! packing the same TOML twice produces bit-identical bytes (pinned by
//! this module's own determinism test).
//!
//! # Equivalence
//!
//! [`SamView::matching_stats`] walks the identical automaton with the
//! identical reference control flow as [`crate::Sam::matching_stats`] —
//! only the transition lookup differs (binary search over a sorted CSR
//! slice instead of a `HashMap` probe), which cannot change which state
//! is reached. Parity is pinned by tests comparing both walks over the
//! same packs, and by the CLI's byte-identical fixture battery.

use crate::dms::{DmsIndex, ModelFamily, Sam};
use crate::{PackError, Sha256};

/// The 8-byte magic every DMS binary artifact starts with.
const MAGIC: [u8; 8] = *b"FRDMSIDX";

/// This module's on-disk format version: bumped if the layout above ever
/// changes shape. Bumped to `2` when [`POOLED_MACHINE_TAG`]'s stream was
/// added (see the module docs' "Format version 2" section).
const FORMAT_VERSION: u16 = 2;

/// The stream tag for [`crate::DmsIndex::pooled_machine_sam`] — one past
/// the last per-family tag (`1 + ModelFamily::ALL` position), so it never
/// collides with a real family's tag regardless of how many families a
/// pack defines. Written as a literal (not `1 + ModelFamily::ALL.len()
/// as u32`) to keep this a `usize`-cast-free `const`; the assertion right
/// below pins it against drift if [`ModelFamily::ALL`] ever grows.
const POOLED_MACHINE_TAG: u32 = 6;
const _: () = assert!(
    POOLED_MACHINE_TAG as usize == 1 + ModelFamily::ALL.len(),
    "POOLED_MACHINE_TAG must stay one past the last per-family tag"
);

/// A sha256 digest is recorded as lowercase hex (matching
/// [`Sha256`]'s `Display`), not raw bytes, so a hex dump of the header
/// stays human-legible — same choice as `friction-nlp`'s weight headers.
const SHA256_HEX_LEN: usize = 64;

/// The fixed-length prefix: magic + version + source sha256 hex.
const HEADER_LEN: usize = 8 + 2 + SHA256_HEX_LEN;

/// The `link` value serialized for the root state's `None` — no real
/// state index is ever `u32::MAX` (a real automaton of that size would
/// dwarf addressable memory long before).
const ROOT_LINK_SENTINEL: u32 = u32::MAX;

/// Bytes per serialized transition: `label: u32` + `target: u32`.
const TRANS_ENTRY_LEN: usize = 8;

/// Errors reading a DMS binary artifact.
///
/// Never expected for the vendored artifact (covered by this crate's own
/// round-trip and drift tests): only for corrupted or hand-edited input.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum DmsBinError {
    /// Shorter than the fixed header: not an artifact this module wrote.
    #[error("DMS artifact truncated: {len} byte(s), need at least {min}")]
    Truncated { len: usize, min: usize },
    /// The first 8 bytes are not `FRDMSIDX`.
    #[error("DMS artifact has an unrecognized magic")]
    BadMagic,
    /// The version field isn't [`FORMAT_VERSION`].
    #[error("DMS artifact format version {found} is unsupported (expected {expected})")]
    VersionMismatch { found: u16, expected: u16 },
    /// The sha256 field isn't valid UTF-8.
    #[error("DMS artifact's recorded sha256 is not valid UTF-8")]
    BadSha256,
    /// A section was structurally inconsistent (a length running past the
    /// end of the artifact, an unknown stream tag, ...).
    #[error("DMS artifact payload is malformed: {0}")]
    Malformed(&'static str),
}

// ---------------------------------------------------------------------
// Packing (build side — `corpus-tool dms-pack`).
// ---------------------------------------------------------------------

/// Packs `toml_text` (a `dms-index-v1` pack) into this module's binary
/// layout.
///
/// Parses it with [`DmsIndex::parse`], builds every stream's [`Sam`]
/// exactly as the runtime used to, and serializes the finished automata
/// with the source's sha256 recorded in the header.
///
/// # Errors
/// Returns [`PackError`] if `toml_text` is not a valid `dms-index-v1`
/// pack — see [`DmsIndex::parse`]. Serialization itself cannot fail.
pub fn pack_dms_index_bin(toml_text: &str) -> Result<Vec<u8>, PackError> {
    let index = DmsIndex::parse(toml_text)?;
    let sha_hex = Sha256::of_bytes(toml_text.as_bytes()).to_string();

    let mut out = Vec::new();
    out.extend_from_slice(&MAGIC);
    out.extend_from_slice(&FORMAT_VERSION.to_le_bytes());
    out.extend_from_slice(sha_hex.as_bytes());

    write_vocab(&mut out, &index);

    let mut streams: Vec<(u32, &Sam)> = std::iter::once((0u32, index.human_sam()))
        .chain(index.family_sams().map(|(family, sam)| {
            let position = ModelFamily::ALL
                .iter()
                .position(|&f| f == family)
                .expect("ModelFamily::ALL is exhaustive by definition");
            (u32_from(position + 1), sam)
        }))
        .collect();
    streams.push((POOLED_MACHINE_TAG, index.pooled_machine_sam()));
    write_u32(&mut out, u32_from(streams.len()));
    for (tag, sam) in streams {
        write_u32(&mut out, tag);
        write_sam(&mut out, sam);
    }
    Ok(out)
}

/// Serializes the vocab section: see the module docs for the layout.
fn write_vocab(out: &mut Vec<u8>, index: &DmsIndex) {
    let vocab = index.vocab();
    let n = vocab.len();
    write_u32(out, u32_from(n));

    let mut pool: Vec<u8> = Vec::new();
    let mut offsets: Vec<u32> = Vec::with_capacity(n + 1);
    offsets.push(0);
    for id in 0..n {
        let token = vocab
            .token_of(u32_from(id))
            .expect("every id below Vocab::len resolves");
        pool.extend_from_slice(token.as_bytes());
        offsets.push(u32_from(pool.len()));
    }
    for offset in &offsets {
        write_u32(out, *offset);
    }
    write_u32(out, u32_from(pool.len()));
    out.extend_from_slice(&pool);

    // First-id-wins duplicate collapse, in BTreeMap (byte-string) order —
    // exactly the resolution `Vocab::id_of` documents.
    let mut first_by_text: std::collections::BTreeMap<&str, u32> =
        std::collections::BTreeMap::new();
    for id in 0..n {
        let token = vocab
            .token_of(u32_from(id))
            .expect("every id below Vocab::len resolves");
        first_by_text.entry(token).or_insert_with(|| u32_from(id));
    }
    write_u32(out, u32_from(first_by_text.len()));
    for &id in first_by_text.values() {
        write_u32(out, id);
    }
}

/// Serializes one automaton: see the module docs for the layout.
fn write_sam(out: &mut Vec<u8>, sam: &Sam) {
    let state_count = sam.state_count();
    write_u32(out, u32_from(state_count));
    for s in 0..state_count {
        write_u32(out, sam.len_of(s));
    }
    for s in 0..state_count {
        write_u32(out, sam.link_of(s).unwrap_or(ROOT_LINK_SENTINEL));
    }

    let per_state: Vec<Vec<(u32, u32)>> = (0..state_count)
        .map(|s| sam.sorted_transitions(s))
        .collect();
    let mut cumulative: u32 = 0;
    write_u32(out, cumulative);
    for transitions in &per_state {
        cumulative += u32_from(transitions.len());
        write_u32(out, cumulative);
    }
    for transitions in &per_state {
        for &(label, target) in transitions {
            write_u32(out, label);
            write_u32(out, target);
        }
    }
}

/// Appends `value` little-endian.
fn write_u32(out: &mut Vec<u8>, value: u32) {
    out.extend_from_slice(&value.to_le_bytes());
}

/// `usize -> u32` with the one honest justification every count in this
/// artifact shares.
fn u32_from(value: usize) -> u32 {
    u32::try_from(value).expect("a DMS pack's counts stay far below u32::MAX")
}

